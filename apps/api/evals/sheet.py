"""Write the review sheet and blank label files. Labels already filled in are kept.

uv run python -m evals.sheet
"""

import csv
from pathlib import Path

from evals import dataset


def _merge(
    path: Path, fields: list[str], rows: list[dict[str, str]], key: tuple[str, str], same: str
) -> int:
    """Write rows, carrying over filled-in columns while the text they judged is unchanged."""
    old = {(r[key[0]], r[key[1]]): r for r in dataset.read_rows(path)}
    cleared = 0
    for row in rows:
        previous = old.get((row[key[0]], row[key[1]]))
        if previous is None:
            continue
        if previous.get(same) != row[same]:
            cleared += 1  # the text changed, so the old judgment no longer applies
            continue
        row.update({k: v for k, v in previous.items() if k in fields and row.get(k, "") == ""})
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    return cleared


def _numbered(lines: list) -> str:
    return "\n".join(f"{line.number:>3}  {line.text}" for line in lines)


def write(root: Path = dataset.ROOT) -> int:
    """Returns how many labels were cleared because their text changed."""
    matching = dataset.matching_cases(root)
    extraction = dataset.extraction_cases(root)

    cleared = _merge(
        root / "matching" / "labels.csv",
        dataset.MATCHING_FIELDS,
        [
            {"case_id": c.id, "number": str(n), "requirement": text}
            | {"verdict": "", "resume_lines": "", "note": ""}
            for c in matching
            for n, text in enumerate(c.requirements, start=1)
        ],
        ("case_id", "number"),
        "requirement",
    )
    cleared += _merge(
        root / "extraction" / "labels.csv",
        dataset.EXTRACTION_FIELDS,
        [
            {"case_id": c.id, "line": str(x.number), "text": x.text, "label": "", "note": ""}
            for c in extraction
            for x in c.lines
        ],
        ("case_id", "line"),
        "text",
    )

    sheet = ["# Review sheet", "", "Generated by `python -m evals.sheet`. See README.md.", ""]
    sheet += ["## Matching", ""]
    for case in matching:
        wanted = "\n".join(f"{n}. {t}" for n, t in enumerate(case.requirements, start=1))
        sheet += [f"### {case.id} (as of {case.as_of})", "", "```text", _numbered(case.resume)]
        sheet += ["```", "", wanted, ""]
    sheet += ["## Extraction", ""]
    for case in extraction:
        sheet += [f"### {case.id}", "", "```text", _numbered(case.lines), "```", ""]
    (root / "review.md").write_text("\n".join(sheet), encoding="utf-8")
    return cleared


if __name__ == "__main__":
    count = write()
    print("Wrote review.md, matching/labels.csv and extraction/labels.csv.")
    if count:
        print(f"{count} label(s) were cleared because their text changed; please redo them.")
